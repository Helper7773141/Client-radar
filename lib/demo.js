function normalize(value) {
  return String(value || "").trim().toLowerCase().replace(/[«»"']/g, "");
}

function isoAgo(days) {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() - days);
  return d.toISOString();
}

export function findDemoCompany(query) {
  const q = normalize(query);
  return COMPANIES.find((item) => item.aliases.some((alias) => normalize(alias) === q)) || null;
}

export function buildDemoEvents(entry) {
  if (!entry) return [];
  return entry.signals.map((signal, index) => ({
    id: "demo-" + entry.key + "-" + index,
    title: "Демонстрационный пример: сообщение о " + signal[0],
    date: isoAgo(index + 1),
    sourceName: "Demo dataset",
    url: null,
    isDemo: true,
    hintedCategory: signal[1],
  }));
}
