export function classifySignal(title) {
  const text = String(title || "");
  let best = null;
  let bestScore = 0;

  for (const rule of RULES) {
    const score = rule.patterns.reduce((sum, pattern) => sum + (pattern.test(text) ? 1 : 0), 0);
    if (score > bestScore) {
      best = rule;
      bestScore = score;
    }
  }

  const rule = best || DEFAULT_RULE;
  return {
    category: rule.category,
    products: rule.products,
    bank: rule.bank,
    investor: rule.investor,
    owner: rule.owner,
    confidence: bestScore >= 2 ? "Высокая" : bestScore === 1 ? "Средняя" : "Низкая",
  };
}
